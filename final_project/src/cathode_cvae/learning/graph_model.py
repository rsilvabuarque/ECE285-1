"""Distance-based message passing for a *fixed chemically labelled parent*.

The encoder sees the complete training mask, including vacant ion-site nodes.
Its only output to a generative decoder is the latent Gaussian. Fixed host
species and radial distances are explicit; coordinates are never generated by
this encoder. Node relabelling invariance is not full-network equivariance.
"""

import numpy as np
import torch
from torch import nn


class GraphOccupationEncoder(nn.Module):
    """Two message-passing layers with six smooth distance channels.

    Messages use learned channel-specific linear maps and fixed normalized RBF
    adjacency matrices. Periodic image contributions are summed *after* their
    individual distances are expanded. Pool mobile and fixed-host nodes
    separately, preserving host chemistry without passing site embeddings
    around the latent bottleneck.
    """
    def __init__(self, graph, condition_dim, latent_dim, hidden_dim=32, radial_channels=6):
        super().__init__()
        self.n_sites = graph.n_sites
        self.latent_dim = int(latent_dim)
        if self.latent_dim <= 0:
            raise ValueError("a graph variational encoder needs positive latent_dim")
        self.hidden_dim = int(hidden_dim)
        n = len(graph.parent.numbers)
        self.register_buffer("numbers", torch.as_tensor(graph.parent.numbers, dtype=torch.long))
        self.register_buffer("mobile_indices", torch.as_tensor(graph.parent.mobile_indices, dtype=torch.long))
        self.register_buffer("host_indices", torch.as_tensor(graph.parent.host_indices, dtype=torch.long))
        is_mobile = np.zeros(n, dtype=float)
        is_mobile[graph.parent.mobile_indices] = 1.
        self.register_buffer("is_mobile", torch.as_tensor(is_mobile, dtype=torch.float32))
        centers = np.linspace(0., graph.cutoff_A, radial_channels)
        width = graph.cutoff_A / max(1, radial_channels - 1)
        # Cosine envelope vanishes smoothly at the chosen cutoff.
        radial = np.exp(-.5 * ((graph.distances_A[:, None] - centers) / width) ** 2)
        radial *= .5 * (1 + np.cos(np.pi * graph.distances_A[:, None] / graph.cutoff_A))
        adjacency = np.zeros((radial_channels, n, n), dtype=float)
        for k in range(radial_channels):
            np.add.at(adjacency[k], (graph.source, graph.destination), radial[:, k])
        degree = adjacency.sum(axis=-1)
        adjacency = np.divide(adjacency, degree[..., None], out=np.zeros_like(adjacency), where=degree[..., None] > 0)
        self.register_buffer("radial_adjacency", torch.as_tensor(adjacency, dtype=torch.float32))
        self.register_buffer("radial_degrees", torch.as_tensor(np.log1p(degree.T), dtype=torch.float32))
        self.element_embedding = nn.Embedding(119, 12)
        self.input = nn.Linear(12 + 2 + radial_channels, hidden_dim)
        self.self_layers = nn.ModuleList(nn.Linear(hidden_dim, hidden_dim) for _ in range(2))
        self.message_layers = nn.ModuleList(nn.Linear(radial_channels * hidden_dim, hidden_dim, bias=False) for _ in range(2))
        self.output = nn.Sequential(nn.Linear(2 * hidden_dim + condition_dim, 64), nn.SiLU())
        self.mu = nn.Linear(64, latent_dim)
        self.logvar = nn.Linear(64, latent_dim)

    def forward(self, occupancy, condition):
        if occupancy.ndim != 2 or occupancy.shape[1] != self.n_sites or len(condition) != len(occupancy):
            raise ValueError("graph encoder mask/condition shape differs from its parent")
        b = len(occupancy)
        present = occupancy.new_ones((b, len(self.numbers)))
        present[:, self.mobile_indices] = occupancy
        element = self.element_embedding(self.numbers)[None].expand(b, -1, -1)
        site = self.is_mobile.to(dtype=occupancy.dtype)[None, :, None].expand(b, -1, -1)
        degree = self.radial_degrees.to(dtype=occupancy.dtype)[None].expand(b, -1, -1)
        features = torch.cat((element, site, present[:, :, None], degree), dim=-1)
        h = torch.nn.functional.silu(self.input(features))
        adjacency = self.radial_adjacency.to(dtype=h.dtype)
        for own, message in zip(self.self_layers, self.message_layers):
            aggregation = torch.einsum("kij,bjh->bikh", adjacency, h).flatten(-2)
            h = torch.nn.functional.silu(own(h) + message(aggregation))
        mobile = h[:, self.mobile_indices].mean(dim=1)
        host = h[:, self.host_indices].mean(dim=1) if len(self.host_indices) else torch.zeros_like(mobile)
        pooled = self.output(torch.cat((mobile, host, condition), dim=-1))
        return self.mu(pooled), self.logvar(pooled).clamp(-12, 8)

